#!/usr/bin/env bash
# Bring up a 3-node tier-0 cluster: 2 control-plane + 1 worker, each a
# privileged systemd container with sshd, reachable over SSH with a generated
# ed25519 key. Writes e2e/tier0/config.toml pointing at the container IPs.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
IMAGE="kurin/tier0-node:local"
NETWORK="kurin-tier0"
NODES=(master01 master02 worker01)
KEYS="$HERE/keys"
CONFIG="$HERE/config.toml"

log() { printf '\033[1;34m[tier0]\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m[tier0] %s\033[0m\n' "$*" >&2; exit 1; }

command -v docker >/dev/null || die "docker not found"

# --- image -------------------------------------------------------------------
if ! docker image inspect "$IMAGE" >/dev/null 2>&1; then
    log "building $IMAGE (systemd + sshd)"
    docker build -q -t "$IMAGE" "$HERE" >/dev/null
fi

# --- network -----------------------------------------------------------------
if ! docker network inspect "$NETWORK" >/dev/null 2>&1; then
    # Let docker pick a free subnet; hosts already squat on some 172.x pools,
    # so pinning a subnet breaks `docker network create`.
    log "creating network $NETWORK"
    docker network create "$NETWORK" >/dev/null
fi

# --- ssh key -----------------------------------------------------------------
mkdir -p "$KEYS"
chmod 700 "$KEYS"
if [[ ! -f "$KEYS/id_ed25519" ]]; then
    log "generating test keypair"
    ssh-keygen -q -t ed25519 -N '' -C "kurin-tier0" -f "$KEYS/id_ed25519"
fi
PUBKEY="$(cat "$KEYS/id_ed25519.pub")"

# --- containers --------------------------------------------------------------
for n in "${NODES[@]}"; do
    ctr="kurin-tier0-$n"
    docker rm -f "$ctr" >/dev/null 2>&1 || true
    log "starting $ctr"
    docker run -d --name "$ctr" \
        --hostname "$n" \
        --privileged \
        --cgroupns=host \
        -v /sys/fs/cgroup:/sys/fs/cgroup:rw \
        --network "$NETWORK" \
        -p 127.0.0.1::22 \
        "$IMAGE" >/dev/null
done

# --- inject key + wait for sshd ---------------------------------------------
for n in "${NODES[@]}"; do
    ctr="kurin-tier0-$n"
    # sshd reads authorized_keys from root's home once it is up; do not rely on
    # systemd being ready first, the directory exists in the image already.
    docker exec "$ctr" sh -c "printf '%s\n' '$PUBKEY' > /root/.ssh/authorized_keys && chmod 600 /root/.ssh/authorized_keys"
done

log "waiting for sshd"
for n in "${NODES[@]}"; do
    ctr="kurin-tier0-$n"
    ip="$(docker inspect -f '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}' "$ctr")"
    [[ -n "$ip" ]] || die "no IP for $ctr"
    ok=0
    for _ in $(seq 1 60); do
        if ssh -i "$KEYS/id_ed25519" -o BatchMode=yes -o ConnectTimeout=2 \
              -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null \
              "root@$ip" true >/dev/null 2>&1; then
            ok=1
            break
        fi
        sleep 1
    done
    [[ $ok == 1 ]] || die "sshd on $ctr ($ip) did not become ready"
    log "$n reachable at $ip"
done

# --- config ------------------------------------------------------------------
node_block() {
    local name="$1" role="$2"
    local ip
    ip="$(docker inspect -f '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}' "kurin-tier0-$name")"
    cat <<EOF

[nodes.$name]
address = "$ip"
role = "$role"
EOF
}

# vip: one unused address beside the nodes (docker hands nodes the low octets).
m1_ip="$(docker inspect -f '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}' kurin-tier0-master01)"
VIP="${m1_ip%.*}.250"
for n in "${NODES[@]}"; do
    n_ip="$(docker inspect -f '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}' "kurin-tier0-$n")"
    [[ "$n_ip" != "$VIP" ]] || die "vip $VIP collides with $n"
done

log "writing $CONFIG"
{
    cat <<EOF
# Generated by e2e/tier0/up.sh - do not edit, do not commit.
version = "v1alpha1"
name = "tier0"

[kubernetes]
version = "1.33.1"

[network]
pod-cidr = "10.233.64.0/18"
service-cidr = "10.233.0.0/18"
dns-domain = "cluster.local"

[network.cni]
kind = "calico"

[ssh]
user = "root"
port = 22

[ssh.auth]
method = "private_key"
key-path = "$KEYS/id_ed25519"

[ha]
vip = "$VIP"
EOF
    node_block master01 control-plane
    node_block master02 control-plane
    node_block worker01 worker
} > "$CONFIG"

log "tier0 up: ${NODES[*]}"